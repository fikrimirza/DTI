class Jet4Tests(unittest.TestCase):
    def test_tables_and_rows(self):
        with Jet4Database(EPWIN) as db:
            self.assertEqual(db.table_names(), ["AEPStim", "Amplifiers", "BioMAPStim", "EPData",
                                                "Labels", "MarkedPoints", "Records"])
            recs = list(db.rows("Records"))
            self.assertEqual(len(recs), 5)
            r = [x for x in recs if x["RecordID"] == R4][0]
            # 2 banks x 1024 int32 + headers -> multi page long value
            self.assertEqual(len(r["Data"]), 4 + 2 * (12 + 4 * 1024))
            self.assertAlmostEqual(float32_clean(r["EpochTime"]), 85.33)
            self.assertEqual(r["PrePostPoints"], -720)

    def test_text_memo_dates(self):
        with Jet4Database(PTI) as db:
            pats = {p["PatientID"]: p for p in db.rows("Patients")}
            self.assertEqual(pats["TEST002"]["FirstName"], "Kedua éè 中")
            memo = pats["TEST001"]["Comment"]
            self.assertTrue(memo.startswith("Catatan uji 0. "))
            self.assertTrue(memo.endswith("Catatan uji 699. "))
            self.assertEqual(pats["TEST001"]["Birthdate"].year, 2019)
            self.assertIsNone(pats["TEST002"]["Comment"])

    def test_helpers(self):
        self.assertEqual(decode_text(b"\xff\xfeAB"), "AB")
        self.assertEqual(decode_text("x中".encode("utf-16-le")), "x中")
        self.assertEqual(ole_date(0.5).hour, 12)
        self.assertEqual(ole_date(-1.25).strftime("%Y-%m-%d %H:%M"), "1899-12-29 06:00")
        self.assertEqual(float32_clean(struct.unpack("<f", struct.pack("<f", 74.67))[0]), 74.67)

    def test_not_an_mdb(self):
        with tempfile.NamedTemporaryFile(suffix=".mdb", delete=False) as fh:
            fh.write(b"x" * 8192)
        try:
            with self.assertRaises(Exception):
                Jet4Database(fh.name)
        finally:
            os.unlink(fh.name)


class ModelTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.db = BiologicDatabase.from_folder(FIX)

    def rec(self, rid):
        return self.db.find(rid)

    def test_join_and_order(self):
        self.assertEqual(len(self.db.records), 5)
        r1 = self.rec(R1)
        self.assertEqual(r1.patient.patient_id, "TEST001")
        self.assertEqual(r1.test.technician, "Teknisi Uji")
        self.assertEqual([r.index for r in self.db.records_for(r1.blscid, "EP00001")], [1, 2, 3])
        names = [p.last_name for p in self.db.patient_list()]
        self.assertIn("(not in BLPatients)", names)  # record without patient

    def test_scaling_and_time_axis(self):
        r1 = self.rec(R1)
        w = r1.waveforms[0]
        self.assertAlmostEqual(w.scale_uv, UV, places=12)
        self.assertAlmostEqual(ad_to_uv_scale(16, 100000), UV, places=12)
        t = r1.times_ms()
        self.assertAlmostEqual(t[0], -749 / 48.0 - 0.8, places=9)
        self.assertAlmostEqual(t[1] - t[0], 74.67 / 512, places=6)
        self.assertAlmostEqual(r1.times_ms(insert_delay_correction=False)[0], -749 / 48.0, places=9)
        self.assertAlmostEqual(1000.0 / (r1.times_ms(timebase="hardware")[1] - t[0]), 48000 / 7, places=3)
        # synthetic signal: 0.2 uV 100 Hz sine after onset + 7 counts DC
        self.assertAlmostEqual(w.uv[0], 7 * UV, places=9)
        self.assertLess(abs(max(w.uv) - 0.2 - 7 * UV), 0.002)

    def test_bioMAP_window(self):
        r4 = self.rec(R4)
        t = r4.times_ms()
        self.assertAlmostEqual(t[0], -15.8, places=6)
        self.assertEqual(r4.test_type_name, "BioMAP")
        self.assertTrue(r4.is_speech)
        self.assertEqual(r4.banks, [10, 11])

    def test_stimulus_text(self):
        r1, r3 = self.rec(R1), self.rec(R3)
        self.assertEqual(r1.stimulus, "Custom: da.wav")
        self.assertEqual(r1.polarity, "Rarefaction")
        self.assertEqual(r1.intensity, "80 dB SPL")
        self.assertEqual(r1.transducer, "Insert Earphone (ER3)")
        self.assertEqual(r1.ear, "Left")
        self.assertTrue(r1.is_speech)
        self.assertFalse(r3.is_speech)
        self.assertEqual(r3.stimulus, "Click")
        self.assertEqual(r3.polarity, "Alternating")
        self.assertEqual(r3.intensity, "70 dB nHL")
        self.assertEqual(r3.waveform(1, 10).bank_name, "Added (Cond+Rare)")
        self.assertEqual(r3.waveform(1, 10).averages, 1536)

    def test_marked_point_matches_sample(self):
        r3 = self.rec(R3)
        m = r3.marked_points[0]
        t = r3.times_ms()
        self.assertEqual(m.label, "V")
        self.assertAlmostEqual(t[112], m.latency_ms, places=4)
        self.assertAlmostEqual(r3.waveform(1, 10).uv[112], m.amplitude_uv, places=5)

    def test_blob_errors(self):
        with self.assertRaises(DataFormatError):
            decode_data_blob(b"")
        bad = struct.pack("<iiii", 10, 1, 1, 1000)  # claims 1000 samples, has none
        with self.assertRaises(DataFormatError):
            decode_data_blob(bad)
        hdr, blocks = decode_data_blob(struct.pack("<iiiiii", 10, 1, 10, 2, 5, -6))
        self.assertEqual((hdr, blocks[0][0], blocks[0][1], list(blocks[0][2])), (10, 1, 10, [5, -6]))


class ExportTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.db = BiologicDatabase.from_folder(FIX)
        cls.tmp = tempfile.mkdtemp(prefix="aep2cabr_test_")

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def test_avg_roundtrip(self):
        r3 = self.db.find(R3)
        es = record_to_export(r3)
        path = os.path.join(self.tmp, "r3.avg")
        neuroscan.write_avg(path, es)
        a = neuroscan.read_avg(path)
        self.assertEqual((a.pnts, a.nchan, a.rate), (256, 4, 24015))
        self.assertEqual(a.labels, ["C1B1", "C1B2", "C1B10", "C1B11"])
        for ch, w in zip(a.data, r3.waveforms):
            self.assertLess(max(abs(x - y) for x, y in zip(ch, w.uv)), 1e-6)
        for x, y in zip(a.times_ms(), r3.times_ms()):
            self.assertAlmostEqual(x, y, places=4)
        size = os.path.getsize(path)
        self.assertEqual(size, 900 + 4 * 75 + 4 * (5 + 256 * 4) + 4 * 256 * 4)

    def test_bank_selection_and_baseline(self):
        r3 = self.db.find(R3)
        es = record_to_export(r3, banks=[10], baseline="mean")
        self.assertEqual([c.label for c in es.channels], ["C1B10"])
        self.assertAlmostEqual(sum(es.channels[0].values), 0.0, places=6)
        r1 = self.db.find(R1)
        es = record_to_export(r1, baseline="prestim")
        pre = [v for v, t in zip(es.channels[0].values, es.times_ms) if t < 0]
        self.assertAlmostEqual(sum(pre) / len(pre), 0.0, places=9)
        with self.assertRaises(ValueError):
            record_to_export(r1, banks=[11])

    def test_combine(self):
        r1, r2 = self.db.find(R1), self.db.find(R2)
        add = combine_records([r1, r2], "add")
        sub = combine_records([r1, r2], "subtract")
        n1, n2 = r1.waveforms[0].averages, r2.waveforms[0].averages
        a, b = r1.waveforms[0].uv, r2.waveforms[0].uv
        for i in (0, 200, 400):
            self.assertAlmostEqual(add.channels[0].values[i], (n1 * a[i] + n2 * b[i]) / (n1 + n2), places=9)
            self.assertAlmostEqual(sub.channels[0].values[i], (a[i] - b[i]) / 2, places=9)
        # opposite polarity sines: added ~ DC only, subtracted keeps the sine
        self.assertLess(max(abs(v - 7 * UV) for v in add.channels[0].values), 0.003)
        self.assertGreater(max(sub.channels[0].values), 0.19)
        self.assertEqual(add.channels[0].averages, n1 + n2)
        with self.assertRaises(ValueError):
            combine_records([r1, self.db.find(R3)], "add")
        with self.assertRaises(ValueError):
            combine_records([r1], "subtract")

    def test_text_outputs(self):
        r1 = self.db.find(R1)
        es = record_to_export(r1)
        p = os.path.join(self.tmp, "r1.txt")
        textout.write_single_column(p, es)
        vals = [float(x) for x in slurp(p).split()]
        self.assertEqual(len(vals), 512)
        self.assertAlmostEqual(vals[300], es.channels[0].values[300], places=5)
        call = textout.bt_txt2avg_call(es, "r1.txt")
        self.assertTrue(call.startswith("bt_txt2avg('r1.txt', 6856.837, -16.4042, "))
        c = os.path.join(self.tmp, "r1.csv")
        textout.write_table(c, es)
        lines = slurp(c).splitlines()
        self.assertEqual(lines[0], "Time(ms),C1B1(uV)")
        self.assertEqual(len(lines), 513)

    def test_ascii(self):
        recs = [self.db.find(R3), self.db.find(R1)]
        txt = to_string(recs, AsciiOptions())
        self.assertIn("Patient ID\tLast Name", txt)
        self.assertIn("Chan 1 Bank 10 V Latency(ms)", txt)
        self.assertIn("Latency(ms)\tChan 1 Bank 1 Amplitude(uV)", txt)
        rows = to_string(recs[:1], AsciiOptions(columns=False, tab_delimited=False, quotes=True))
        self.assertIn('"Chan 1 Bank 11 Amplitude(uV)"', rows)
        self.assertEqual(vb_format(1.0), "1.0")
        self.assertEqual(vb_format(-16.404166), "-16.4042")
        self.assertEqual(vb_format(2.5, 1, 2), "2.5")

    def test_anonymize_leaks_nothing(self):
        out = os.path.join(self.tmp, "anon")
        recs = self.db.records
        files = cli.export_records(recs, list(range(1, len(recs) + 1)), "avg", out,
                                   anonymize=True, log=lambda *a: None)
        files += cli.export_records(recs, list(range(1, len(recs) + 1)), "txt", out,
                                    anonymize=True, log=lambda *a: None)
        files += cli.export_records(recs, [1] * len(recs), "ascii", os.path.join(out, "a.txt"),
                                    anonymize=True, log=lambda *a: None)
        self.assertTrue(files)
        for fn in os.listdir(out):
            self.assertNotIn("TEST00", fn)
            data = slurp(os.path.join(out, fn), "rb")
            for secret in (b"TEST001", b"TEST002", b"PASIEN", b"DUMMY", b"Contoh", b"2022", b"Teknisi"):
                self.assertNotIn(secret, data, "%s leaks %r" % (fn, secret))


class StimulusTests(unittest.TestCase):
    def test_wav2avg_and_resample(self):
        tmp = tempfile.mkdtemp(prefix="aep2cabr_wav_")
        try:
            wav = os.path.join(tmp, "da.wav")
            fs, f0, n = 48000, 100.0, 4800
            with wave.open(wav, "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(2)
                w.setframerate(fs)
                w.writeframes(b"".join(struct.pack("<h", int(16000 * math.sin(2 * math.pi * f0 * i / fs)))
                                       for i in range(n)))
            out = os.path.join(tmp, "da.avg")
            es = stimulus.wav2avg(wav, out)
            a = neuroscan.read_avg(out)
            self.assertEqual((a.pnts, a.rate), (n, fs))
            self.assertAlmostEqual(a.data[0][120], 16000 * math.sin(2 * math.pi * f0 * 120 / fs) // 1 / 32768, places=4)
            es2 = stimulus.wav_to_export(wav, rate=12000, prestim_ms=5)
            self.assertEqual(es2.n_points, 60 + 1200)
            self.assertAlmostEqual(es2.xmin_ms, -5.0)
            v = es2.channels[0].values[60:]
            # band-limited resampling keeps the 100 Hz sine
            for i in (300, 450, 700):
                self.assertAlmostEqual(v[i], 16000 / 32768 * math.sin(2 * math.pi * f0 * i / 12000), places=2)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


class CliTests(unittest.TestCase):
    def run_cli(self, *args):
        buf = io.StringIO()
        with redirect_stdout(buf):
            cli.main(list(args))
        return buf.getvalue()

    def test_list_export_combine(self):
        out = self.run_cli("list", "--data", FIX)
        self.assertIn("5 record(s)", out)
        self.assertIn("cABR", out)
        out = self.run_cli("list", "--data", FIX, "--cabr")
        self.assertIn("4 record(s)", out)
        tmp = tempfile.mkdtemp(prefix="aep2cabr_cli_")
        try:
            self.run_cli("export", "--epwin", EPWIN, "--cabr", "-f", "avg", "-o", tmp)
            avgs = sorted(f for f in os.listdir(tmp) if f.endswith(".avg"))
            self.assertEqual(len(avgs), 5)  # R4 has 2 banks
            self.assertTrue(os.path.exists(os.path.join(tmp, "manifest.csv")))
            info = self.run_cli("avginfo", os.path.join(tmp, avgs[0]))
            self.assertIn("points", info)
            nums = [l.split()[0][1:] for l in self.run_cli("list", "--data", FIX).splitlines()
                    if l.strip().startswith("#") and "Custom: da.wav" in l]
            self.run_cli("combine", "--data", FIX, "-r", *nums, "--mode", "subtract",
                         "-o", os.path.join(tmp, "sub.avg"))
            self.assertEqual(neuroscan.read_avg(os.path.join(tmp, "sub.avg")).labels, ["SUB"])
            self.run_cli("export", "--data", FIX, "--all", "-f", "ascii", "-o", os.path.join(tmp, "x", "a.txt"))
            self.assertTrue(os.path.getsize(os.path.join(tmp, "x", "a.txt")) > 1000)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_parse_numbers(self):
        self.assertEqual(cli.parse_numbers(["1", "3-5", "7,9"]), [1, 3, 4, 5, 7, 9])


